"""深度思考的主代理和四个子代理。

招聘里现在这套叫 Deep Agents（LangChain 的智能体壳，跑在 LangGraph 上）：
- 主代理不自己查数据，用内置的 task 派子代理
- 子代理各管一类 MCP 或接口，查完只交一份短报告，明细不堆进主对话
- 要人选定时，主代理调用 ask，LangGraph 的 interrupt 把图停住

业务顺序是固定的：先排出一整条游玩路线，再沿着路线安排交通、酒店和餐馆。
酒店放在每晚最后一站附近，餐馆放在每顿饭前后那一站附近。
"""


def _files():
    """子代理至少留一个读文件工具，壳才肯装上。提示词里要求它们不要用。

    每个子代理单独一份。共用同一个中间件实例会串状态。
    """
    return FilesystemMiddleware(tools=["read_file"])


# 按模型名挂上壳的配置：拿掉文件和命令工具，关掉通用子代理。只影响这张深度思考图。
register_harness_profile(
    "deepseek:deepseek-v4-flash",
    HarnessProfile(
        excluded_tools=frozenset({
            "ls", "read_file", "write_file", "edit_file", "delete", "glob", "grep", "execute",
        }),
        general_purpose_subagent=GeneralPurposeSubagentProfile(enabled=False),
    ),
)


# ---------- 主代理 ----------

_MAIN = """你是旅行规划的总负责人。用户消息里是一张行程卡片，目的地、日期、天数、人数、预算以卡片为准。
你不自己查数据，用 task 派子代理。必须按下面四步走，不能跳步，也不能调换顺序。

第一步：定路线（只派 route，等它回来再往下）
把这些写进任务：目的地、出发日期、几天几夜、人数里有没有老人小孩、补充条件、已有思路。
route 会交回：每天的天气、按顺序的几站（含开放时间、门票、要不要提前买）、站与站之间怎么走、
每天午饭和晚饭在哪一站附近、每晚落脚点、高德专属地图链接。

第二步：沿路线安排交通、住宿、吃饭（同一条消息里一起派 traffic、stay、food）
- traffic：出发地到目的地的去程，第 1 天第一站之前要到，所以 arrive_before 写第一站开放前约 1 小时。
  回程从目的地回出发地，最后一天最后一站结束后再走，depart_after 写那个时间。
  卡片上写了高铁就只查火车；没写就火车和飞机都查。
- stay：每一晚的日期和落脚点写清楚。相邻两晚落脚点在同一片，就让它按连住查一家。
  每晚上限 = 住宿预算 ÷ 夜数。住宿预算取总预算的三成到四成；卡片没给预算就按每晚 300 元。
- food：每天午饭、晚饭各在哪一站附近写清楚，再写口味和忌口。

第三步：要用户拍板的，调用 ask（每次只问一件事，带价格和时间）
按这个顺序问，一件问完再问下一件：
- 去程和回程（返程）必须分开各问一次，一共两次 ask，不能只问一头，也不能合成一题：
  - 去程：出发地到目的地，traffic 交回的符合条件的车次或航班都放进选项，最多 10 个，标出最快和最便宜
    每个火车选项写出有票的各席别和折后价，例如「G584 汉口09:03→杭州东13:29 二等座有票约352元 一等座无票 商务座剩4张约1066元」
  - 回程：目的地回出发地，写法同去程。去程问完、用户答完，接着就问回程
  - 只查到一趟也要问，选项写「就定这趟」和「换个时间再查」
  - 12306 还没开售查不到，也要问，选项给几个出发时段（上午、下午、晚上），终稿里按选定时段写待核实
- 酒店：每个落脚点都要问（连住的算一个），stay 交回的都放进选项，最多 10 家，写店名、每晚价格、星级、离落脚点多远
- 雨雪、超预算这类问题给 2 到 3 个选项就够
吃饭不问，终稿里直接推荐。
- 预报有雨雪的那天：问是按室内路线走还是调换日期
- 交通、住宿、门票、吃饭加起来超过卡片预算：问是降档还是加预算
去程、回程以外的事，只有一个能用或者根本没查到，就不要问。用户答完按答案改，不要重新查一遍。

第四步：写终稿
1. 开头一行：高德专属地图链接
2. 去程：用户选定的车次或航班、几点从哪站出发、几点到哪站、席别、折后票价（原价和几折放括号里）。
   用户没说席别，就按有票的最便宜席别写，并提醒其他席别的价格
3. 每天一节，当天天气写在开头，再按时间先后写：到哪一站、开放时间、门票和要不要提前买、站间怎么走用多久。
   午饭、晚饭各推荐一家：店名、离哪一站多远、人均、评分，挑评分高、离得近、合口味的。
   后面附一行「备选：」写另外 2 家的店名和人均。整趟每一顿的推荐店都不重复，让每天吃得不一样。
   当晚住宿写用户选定的那家和每晚价格，下面列出其余备选，最多 9 家（店名、每晚价格、星级）。
4. 回程：同去程的写法
5. 花费表：交通、住宿、门票、吃饭、市内交通分开算（交通、住宿按用户选定的算，吃饭按推荐店算），写出合计，再和预算比
查不到的班次、房价、票价、人均写待核实，不要编，也不要自己写「预估多少元」。
花费表里待核实的项单独列出来，不算进合计。景点只写要不要提前买，不做预约。

终稿之后用户再追问（换酒店、换饭店、某天怎么走、某个景点要不要预约、改日期等）：
- 只要问的是对话里没有查过的事实，就必须先派对应的子代理去查，查回来再答，不能凭已有资料或常识回答。
  换酒店、要更便宜的酒店派 stay；换饭店、找某种口味派 food；换车次、改时间派 traffic；
  景点、开放时间、预约、天气、某两站怎么走、改路线派 route。
- 派任务时把用户的新要求、相关日期和落脚点写清楚，子代理看不到前面的对话。
- 用户说「第N天晚饭换成备选里的某家」这种，直接改，不用再查。
- 只有问的是终稿里已经写着的内容（例如「第二天住哪」），才直接回答。
- 改动影响到路线时，只重写受影响的那几天和花费表，不用整篇重写。"""


# ---------- 子代理 ----------

_ROUTE = """你负责排出整条游玩路线。不要问用户，不要读文件，不要编数据。按顺序做：

1. 用 weather 查整段日期的天气，day 写出发日，days 写天数。
2. 用 sight 查城市热门景点，再按卡片里的兴趣、补充条件补查一两次。
   用 notes 搜一两次小红书（「城市 几天 路线」「城市 避坑」），看哪些地方值得去、要排多久。
   sight 给的开放时间缺了，用 place 补；要确认闭馆、预约、限流这类新通知，用 web 搜一次。
   notes 和 web 最多各用 2 次，不要一直搜。
3. 按地理位置把景点分到每一天，每天 3 到 4 站，同一天的站要在同一片区域，不要来回折返。
   第 1 天上午要留给到达，最后一天下午要留给返程，这两天各少排 1 到 2 站。
   有雨雪的那天优先排室内的站（博物馆、美术馆、商业街）。
   有老人小孩时每天不超过 3 站。
   周一闭馆的景点不要排在周一。
4. 用 road 查每天相邻两站怎么走（1.5 公里内用 walking，其余用 transit），把用时写下来。
5. 用 route_map 把每天的站画成一张地图，拿到链接。

交回格式：
天气：逐天一行
第N天（日期 星期几）：
- 站1 开放时间 门票 提前买 → 怎么走 用时 → 站2 ……
- 午饭在：某站附近；晚饭在：某站附近
- 当晚落脚点：某站（最后一天写「返程」）
地图：链接"""

_TRAFFIC = """你只查往返的大交通。不要问用户，不要读文件，不要编班次。

火车：
- 先用 train 按派来的时间条件查一次，城市名就行，同城所有车站都会带上。
- 符合条件的不到 3 趟，就放宽时间（提前或推后 2 小时）再查一次。
- 一趟直达都没有，train 会自动给出中转；也可以直接用 transfer。
- 12306 只卖今天起 14 天内的票。只有工具原话写着没开售，才说没开售。
  工具说服务没连上，就照原话交回，不要说成没开售或没有车。
飞机：卡片没限定高铁时用 flight 查，和火车放在一起比。

去程、回程两头都要查，缺一头不能交回。各交回全部符合时间条件的候选，最多 10 个，按出发时间排，标出最快和最便宜。
不要只挑几趟，用户要自己从里面选。每个候选写：车次或航班、出发站和时间、到达站和时间、历时，
再把 train 给的每个席别都抄下来（商务座、一等座、二等座、无座……）：余票、原价、几折、折后价。
不要只写二等座。二等座无票时，一等座和商务座照样要写，用户可能换席别。
价格按折后价报，原价放括号里；工具写着折扣待核实的，就写原价并注明折扣待核实。"""

_STAY = """你只查酒店。不要问用户，不要读文件，不要编房价。

按派来的每一晚去查：
- hotel 的 near 写当晚落脚点，check_in 写当晚日期，check_out 写第二天。
- 相邻几晚落脚点在同一片时，合成一次查询连住，check_out 写最后一晚的第二天。
- 第一次查到的都超出每晚上限，就把 near 换成离落脚点最近的地铁站或商圈再查一次。
- 优先用 RollingGo 那组：中文店名和每晚展示价。展示价不是锁定报价，写「约」，不要自己改价。
- RollingGo 不足 3 家时才会出现 Pilot（英文店名）。高德那组房价基本是待核实，只用来补距离和电话，不要估价。

每一晚交回全部查到的酒店，最多 10 家：有展示价且在上限内的排前面，超出上限的标出来放后面。
不要只挑几家。每家写：店名、每晚价格（或待核实）、星级、离落脚点多远。"""

_FOOD = """你只查餐馆。不要问用户，不要读文件，不要编店名和人均。

按派来的每一顿去查：food 的 near 写这顿饭前后的那一站，keyword 按口味写（没说口味就写当地菜）。
有忌口的，挑店时避开。
整趟用 notes 搜一次「城市 必吃」看招牌菜和排队情况，候选店要确认营业时间时用 place。
每一顿交回全部符合口味和忌口的餐馆，最多 10 家，当地特色排前面。不要只挑几家。
按「第N天 午饭/晚饭」分开写，不同顿之间尽量不放同一家店。每家写店名、距离、人均、评分。"""


def card_text(card: dict) -> str:
    """把固定行程图里已经记下的条件收成一段，作为深度思考的第一条用户消息。"""
    guide = (card.get("guide") or "").strip()
    lines = [
        # 模型自己不知道今天几号。不写这一行，它会乱算 12306 有没有开售。
        f"今天：{date.today().isoformat()}（12306 卖今天起 14 天内的票）",
        f"目的地：{card.get('destination') or '未说明'}",
        f"出发地：{card.get('origin') or '未说明'}",
        f"出发日期：{card.get('start_date') or '未说明'}",
        f"行程：{card.get('days') or 1}天{card.get('nights') or 0}夜",
        f"去程：{card.get('transport_go') or '未说明'}",
        f"回程：{card.get('transport_back') or '未说明'}",
        f"预算：{card.get('budget_min') or 0}到{card.get('budget_max') or 0}元（0 表示没说）",
        f"人数：大人{card.get('adults') or 0} 小孩{card.get('children') or 0} 老人{card.get('seniors') or 0}",
        f"补充：{card.get('notes') or '无'}",
    ]
    if guide:
        lines.append("已有思路：\n" + guide[:800])
    lines.append("请按四步把衣食住行定下来。")
    return "\n".join(lines)


def build(checkpointer=None):
    """装好主代理。Studio 不传 checkpointer，它自己会接记忆。本地运行才传进来。

    步数封在 120。壳的默认是很大的数，查着查着不停会把这一轮拖死。
    """
    agent = create_deep_agent(
        model=model,
        tools=[ask],
        system_prompt=_MAIN,
        # 主代理只留读文件。查票、查酒店不走文件，走下面的子代理。
        middleware=[_files()],
        subagents=[
            {
                "name": "route",
                "description": "第一步用。参考小红书和网页，排出每天按顺序的景点、天气、站间交通、吃饭和落脚的位置，并画高德地图。追问景点、开放时间、预约、天气、站间怎么走、改路线时也用。",
                "system_prompt": _ROUTE,
                "tools": [weather, sight, place, road, route_map, notes, web],
                "middleware": [_files()],
            },
            {
                "name": "traffic",
                "description": "第二步用。查往返火车（含中转）和飞机，按到达和出发时间筛出候选。追问换车次、改时间时也用。",
                "system_prompt": _TRAFFIC,
                "tools": [train, transfer, flight],
                "middleware": [_files()],
            },
            {
                "name": "stay",
                "description": "第二步用。按每晚落脚点查附近酒店和每晚价格。追问换酒店、要更便宜或更好的酒店时也用。",
                "system_prompt": _STAY,
                "tools": [hotel, place],
                "middleware": [_files()],
            },
            {
                "name": "food",
                "description": "第二步用。按每顿饭前后的那一站查附近餐馆和人均。追问换饭店、找某种口味时也用。",
                "system_prompt": _FOOD,
                "tools": [food, place, notes],
                "middleware": [_files()],
            },
        ],
        checkpointer=checkpointer,
        name="deep_agent",
    )
    return agent.with_config({"recursion_limit": 120})
